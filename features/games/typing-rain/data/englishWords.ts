function toContent(
  words: readonly string[],
  difficulty: TypingContent["difficulty"],
  category: string,
): TypingContent[] {
  return words.map((text, index) => ({
    id: `en-word-${difficulty}-${String(index + 1).padStart(3, "0")}`,
    text,
    language: "en",
    type: "word",
    difficulty,
    category,
    tags: ["english", difficulty],
    enabled: true,
  }));
}
