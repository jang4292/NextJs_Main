function toContent(
  words: readonly string[],
  difficulty: TypingContent["difficulty"],
  category: string,
): TypingContent[] {
  return words.map((text, index) => ({
    id: `ko-word-${difficulty}-${String(index + 1).padStart(3, "0")}`,
    text,
    language: "ko",
    type: "word",
    difficulty,
    category,
    tags: ["한글", difficulty],
    enabled: true,
  }));
}
